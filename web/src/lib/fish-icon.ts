/** 품목 이름에 붙일 상징. 모르면 빈 문자열. */
export function itemIcon(name: string): string {
  const n = (name ?? "").trim();
  if (!n) return "";
  for (const [key, icon] of ICONS) if (n.includes(key)) return icon;
  return "";
}
