//   ⚠ 단위가 `em` 이 아니라 `rem` 인 이유: 같은 폭을 글자 크기가 **다른** 칸에도 똑같이 걸기
//     때문이다. `em` 은 그 칸의 글자 크기를 따라가서, 사진설명(0.95rem)·제목칸(1rem)·본문
//     (1.08rem)이 저마다 다른 폭이 되고 왼쪽 선이 어긋났다. `rem` 은 셋 다 같은 폭이 된다.
//     독자의 글자 크기 설정은 `html { font-size: var(--font-size-base) }` 로 **루트 글자 크기를
//     바꾸므로**(globals.css) rem 도 함께 커진다 — 크게 보기를 켜도 한 줄 글자 수는 그대로다.
//
//   ⚠ 바깥 틀(SHELL)이 읽는 폭보다 넓어야 사진이 본문보다 조금 넓게 앉는다. 신문 지면의 결이다.

