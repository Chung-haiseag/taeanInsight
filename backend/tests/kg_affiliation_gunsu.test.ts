import { describe, it, expect } from "vitest";
import { extractAffiliations } from "../src/kg/affiliation";

// 모순 감사(2026-08-28)에서 '태안군청 군수'가 아닌 사람 93명에게 붙어 있었다.
//   본문은 실제 아카이브 문장이다(지어내지 않는다).
const gov = (body: string) =>
  extractAffiliations(body).filter((c) => c.orgId === "org:taean-gov").map((c) => `${c.personName}/${c.role}`);

describe("군수 소속 — 잘못 붙던 것들", () => {
  it("다른 고장 군수는 태안군청이 아니다 — 전라도 고부군수 조병갑", () => {
    expect(gov("대표적인 것 중 하나가 전라도 고부군수 조병갑의 수세 착취였다")).toEqual([]);
  });

  // ⚠ 한계를 명시해 둔다. '나소열 군수는'처럼 **지역이 어디에도 안 적힌** 다른 지자체 군수는
  //   문장만으로 구별할 방법이 없다(나소열=서천·3건). 사람이 아는 사실이 있어야 한다 —
  //   화면에서는 기사 수가 적어 그대로 드러나고, 어드민 검수에서 걸러야 한다.
  it("지역이 아예 안 적히면 구별하지 못한다(알려진 한계)", () => {
    expect(gov("한 문제점을 안고 있는 것. 나소열 군수는 순회강연회를 통해")).toContain("나소열/군수");
  });

  it("후보·출마예정자는 재임 직함이 아니다 — 강철민", () => {
    expect(gov("[더불어민주당 강철민 태안군수 후보] 더불어민주당")).toEqual([]);
    expect(gov("김기두 의원과 강철민 군수 출마 예정자는 지난")).toEqual([]);
  });

  // ⚠ 규칙 구멍(2026-08-31 정합성 점검). `군수\s*(후보|출마|…)`는 직함에 **바로 붙은** 것만 보는데,
  //   '예비후보'는 '후보' 앞에 '예비'가 끼어 안 걸렸고 '공천신청'은 목록에 아예 없었다.
  //   그래서 이영수(예비후보·기사 3건)·김관섭(입후보예정자·공천신청)이 '태안군청 군수'로 떠 있었다.
  it("예비후보·공천신청도 재임 직함이 아니다", () => {
    expect(gov("국민의 힘 소속 이영수 태안군수 예비후보가 인사말을")).toEqual([]);
    expect(gov("국민의힘, 김세호-한상기-김관섭 태안군수 공천신청")).toEqual([]);
  });

  it("실제 태안군수는 그대로 잡는다", () => {
    expect(gov("권오창 태안군수를 비롯 태안군 선거관리위원회")).toContain("권오창/군수");
    expect(gov("이어 진태구 군수의 축사와 태안군 관계자들이")).toContain("진태구/군수");
  });

  it("부군수는 부군수로 잡는다 — '군수'로 잘리지 않는다", () => {
    expect(gov("지난 6일 태안군청 대강당에서 이수연 부군수를 비롯해")).toContain("이수연/부군수");
  });
});
