import { describe, it, expect } from "vitest";
import { adPrices, PRICE_LABELS } from "../src/archive/ad_prices";

// 시험 문구는 전부 실제 D1 광고 본문의 실측 표본(2026-08-25 조사)에서 그대로 옮겼다.
//   지어낸 예문은 실제 오탐·미탐을 재현하지 못한다 — 광고 분류 작업에서 거듭 확인된 교훈.

const P = (text: string) => adPrices({ title: "", body: text });

describe("전세 — 표기 변형 3종", () => {
  it("'전세 1,500만원'", () => {
    expect(P("입식부엌 기름보일러 전세 1,500만원")).toContainEqual({ label: "전세", man: 1500 });
  });
  it("'전세가 1,100만원'", () => {
    expect(P("61-7 단독주택 전세가 1,100만원")).toContainEqual({ label: "전세", man: 1100 });
  });
  it("글자가 벌어진 '전 세가 500만원'(OCR 분절)", () => {
    expect(P("욕실, 화장실 전 세가 500만원")).toContainEqual({ label: "전세", man: 500 });
  });
  it("'전세금 1,700만원'", () => {
    expect(P("다가구 단층 전세금 1,700만원")).toContainEqual({ label: "전세", man: 1700 });
  });
});

describe("매매 — 매매가·급매", () => {
  it("'매매가 7,000만원'", () => {
    expect(P("302호 34평 매매가 7,000만원")).toContainEqual({ label: "매매", man: 7000 });
  });
  it("'급매 2,000만원'", () => {
    expect(P("개 있는 한옥 1채 급매 2,000만원")).toContainEqual({ label: "매매", man: 2000 });
  });
});

describe("월세 — '월 10만원' 같은 축약형 포함", () => {
  it("'월세 60만원'", () => {
    expect(P("성업중. 월세 60만원")).toContainEqual({ label: "월세", man: 60 });
  });
  it("'보증금 300만원 월 10만원' — 월 뒤 금액은 월세다", () => {
    const r = P("보일러 보증금 300만원 월 10만원");
    expect(r).toContainEqual({ label: "보증금", man: 300 });
    expect(r).toContainEqual({ label: "월세", man: 10 });
  });
  it("'10개월 150만원'은 월세가 아니다(개월 = 기간)", () => {
    expect(P("보증금 100만원에 10개월 150만원").filter((x) => x.label === "월세")).toEqual([]);
  });
});

describe("보증금·권리금·평당", () => {
  it("'보증금 1500만원'", () => {
    expect(P("이층집 권리금, 보증금 1500만원")).toContainEqual({ label: "보증금", man: 1500 });
  });
  it("글자가 벌어진 '보 증금 100만원'(OCR 분절)", () => {
    expect(P("밭 700평 보 증금 100만원")).toContainEqual({ label: "보증금", man: 100 });
  });
  it("'권리금 1,500만원'", () => {
    expect(P("대여가능 시·물·권리금 1,500만원")).toContainEqual({ label: "권리금", man: 1500 });
  });
  it("'평당 200만원'", () => {
    expect(P("화 여인숙(73평) 평당 200만원")).toContainEqual({ label: "평당", man: 200 });
  });
});

describe("잡히면 안 되는 것 — 융자·초봉·판매가·라벨 없는 금액", () => {
  it("'융자 3,000만원'은 대출이지 시세가 아니다", () => {
    expect(P("전세 놓으실분 주택 융자 3,000만원")).toEqual([]);
  });
  it("'초봉: 50만원'은 임금 — 자료가 41건뿐이라 이번엔 뺀다", () => {
    expect(P("일반직: ○○명 ※초봉: 50만원")).toEqual([]);
  });
  it("'판매 45만원'은 물건값 — 품목이 제각각이라 시세가 안 된다", () => {
    expect(P("석궁 구입 65만원 판매 45만원")).toEqual([]);
  });
  it("라벨 없는 '24만원~26만원'은 무엇의 값인지 모른다", () => {
    expect(P("이불+베개+카바 24만원~26만원")).toEqual([]);
  });
});

describe("자릿수 방어 — OCR 오독으로 나온 터무니없는 값 차단", () => {
  it("월세 5,000만원은 오독이다(상한 500)", () => {
    expect(P("월세 5,000만원").filter((x) => x.label === "월세")).toEqual([]);
  });
  it("전세 3만원은 오독이다(하한 30)", () => {
    expect(P("전세 3만원")).toEqual([]);
  });
});

describe("같은 광고 안의 같은 라벨 중복은 한 번만", () => {
  it("'전세 총 1,000만원 ... 전세 1,000만원' 반복", () => {
    const r = P("권리금 시설비 전세 1,000만원 전세 1,000만원");
    expect(r.filter((x) => x.label === "전세")).toHaveLength(1);
  });
});

// 1993년 매매 중앙값이 320만원으로 나와 표본을 열어 보니(2026-08-25) 자동차·중고물품
//   매매가 부동산에 섞여 있었다 — '매매'라는 말 자체는 무엇이든 팔 때 쓴다.
describe("매매는 부동산 문맥이 있어야 시세다", () => {
  it("'프라이드 88년식 매매가 110만원'은 자동차다 — 실측 오탐", () => {
    expect(P("프라이드 88년 8월식 3도어 매매가 110만원")).toEqual([]);
  });
  it("'효성스즈끼 90년식 주행 3,500km 매매가 70만원'도 — 실측 오탐", () => {
    expect(P("효성스즈끼 90년식 주행 3,500km 매매가 70만원")).toEqual([]);
  });
  it("'컨테이너 6평반짜리 매매 230만원' — 평이 있어도 컨테이너는 아니다", () => {
    expect(P("6평반짜리 팝니다 구입 400 매매 230만원 컨테이너")).toEqual([]);
  });
  it("'남양연립 25평 매매 4,300만원'은 부동산이다", () => {
    expect(P("태안 남양연립 25평 매매 4,300만원(가격조절가능)")).toContainEqual({ label: "매매", man: 4300 });
  });
  it("'보령주택 302호 34평 매매가 7,000만원'도", () => {
    expect(P("보령주택 3차 302호 34평 매매가 7,000만원(융2,000포함)")).toContainEqual({ label: "매매", man: 7000 });
  });
});

describe("'전세버스'는 전세가 아니다(여행사 광고)", () => {
  it("전세버스 대여 45만원", () => {
    expect(P("전세버스 45만원 대여").filter((x) => x.label === "전세")).toEqual([]);
  });
});

describe("라벨 목록", () => {
  it("여섯 갈래", () => {
    expect(PRICE_LABELS).toEqual(["전세", "매매", "월세", "보증금", "권리금", "평당"]);
  });
});
