import { describe, it, expect } from "vitest";
import { triageAffiliation, countAffTriage } from "@/kg/affiliation_triage";

// 아래 근거 문장은 2026-08-23 D1 대기열에서 그대로 가져온 실제 값이다.
const C = (person: string, org: string, role: string, ...evidence: string[]) => ({ person, org, role, evidence });

describe("인사발령 기사 — 근거가 이보다 확실할 수 없다", () => {
  it("△·▲ 명단에 조직명+직함+이름이 붙어 있으면 인사발령", () => {
    expect(triageAffiliation(C("이노근", "의회사무과", "과장",
      "사업과장 최영신 ▲원북면장 조항욱 ▲의회사무과장 이노근 ▲의"))).toBe("인사발령");
    expect(triageAffiliation(C("박종관", "민원봉사과", "과장",
      "◆5급 △행정지원과 가재연(승진) △민원봉사과장 박종관 △교"))).toBe("인사발령");
  });

  it("직무대리·파견복귀 같은 표기도 인사발령으로 본다", () => {
    expect(triageAffiliation(C("김수곤", "건설과", "과장",
      "▲정책조정관(태안건설본부) 노춘민 ▲건설과장 김수곤(직무"))).toBe("인사발령");
  });
});

describe("근거 직결 — 조직명과 이름이 한 덩어리", () => {
  it("괄호 표기", () => {
    expect(triageAffiliation(C("조달현", "태안군보건의료원", "원장",
      "진료 받을 수 있는 길이 열렸다. 태안군보건의료원(원장 조달현)은 생체내 전기"))).toBe("근거직결");
    expect(triageAffiliation(C("서용관", "태안소방서", "소장",
      "새벽 3시20분 태안소방서(소장 서용관)의 대형 소방차가 도착하여서야"))).toBe("근거직결");
  });

  it("조직명 다음에 바로 이름이 오는 표기", () => {
    expect(triageAffiliation(C("신현국", "태안군청", "계장",
      "이 자리에서 태안로타리 클럽은 태안군청 신현국 계장, 서부지구대 박귀성 경장에게"))).toBe("근거직결");
    expect(triageAffiliation(C("백정흠", "태안군체육회", "사무국장",
      "350여명이 참석한 이날 주민과의 대화는 태안군체육회 백정흠 사무국장의 사회로"))).toBe("근거직결");
  });

  it("조직명 사이 띄어쓰기가 달라도 같은 것으로 본다", () => {
    expect(triageAffiliation(C("김경년", "태안군체육회", "회장",
      "태안군 체육회 임시총회 개최 태안군 체육회(회장 김경년)는 1"))).toBe("근거직결");
  });
});

describe("사람이 봐야 하는 것", () => {
  // 조병갑은 동학농민운동의 고부군수다. '군수'라는 직함만 보고 태안군청에 붙었다.
  it("조직명이 근거에 아예 없으면 확인 필요", () => {
    expect(triageAffiliation(C("조병갑", "태안군청", "부군수",
      "민란에 관한 보고를 받은 조정에서는 군수 조병갑을 체포 압송하"))).toBe("확인필요");
  });

  it("타 지역 사람이 나열에 섞인 것도 확인 필요", () => {
    expect(triageAffiliation(C("이익창", "태안군청", "군수",
      "태안군 유도협회장 취임식에는 진태구 군수, 이익창 군수를 비롯"))).toBe("확인필요");
  });

  // 조직명은 근거에 있지만 그 이름은 **다른 사람**에게 붙어 있다.
  it("조직명과 이름이 멀리 떨어져 있으면 확인 필요", () => {
    expect(triageAffiliation(C("이기학", "태안군체육회", "회장",
      "배 태안군체육회부회장, 홍성준 태안읍체육회장 이기학 축구"))).toBe("확인필요");
  });

  it("근거가 없으면 확인 필요", () => {
    expect(triageAffiliation(C("아무개", "태안군청", "과장"))).toBe("확인필요");
  });

  it("여러 근거 중 하나만 확실해도 그 갈래로 본다", () => {
    expect(triageAffiliation(C("조달현", "태안군보건의료원", "원장",
      "관계자들이 참석했다", "태안군보건의료원(원장 조달현)은"))).toBe("근거직결");
  });
});

describe("갈래별 집계", () => {
  it("화면에 '몇 건을 자동으로 갈랐는지' 보여줄 수 있다", () => {
    const c = countAffTriage([
      C("이노근", "의회사무과", "과장", "▲의회사무과장 이노근 ▲의"),
      C("조달현", "태안군보건의료원", "원장", "태안군보건의료원(원장 조달현)은"),
      C("조병갑", "태안군청", "부군수", "군수 조병갑을 체포 압송하"),
    ]);
    expect(c).toEqual({ 인사발령: 1, 근거직결: 1, 확인필요: 1 });
  });
});
