describe("관공서 안내·공고는 광고가 아니다", () => {
  it("정부 공고 — '습니다'체라 기사체 보호를 못 받던 것", () => {
    expect(adScore(A("지면 08면", "청량음료 공병보증금 환불 안내",
      "정부에서는 청량음료 빈유리병을 반환하는 소비자에게 일정한 금액(보증금)을 환불하여 주는 청량음료 공병(빈병) 보증금제도를 실시하고 있습니다.\n\n<보증금 및 수수료>\n(단위 : 원)\n병 크기 | 보증금(소비자가 환불 받는 금액) | 수수료(판매업자가 제조업자로부터 받는 금액)\n190ml~300ml미만 | 40원 | 5원")).ad).toBe(false);
  });

  it("군부대 공익 안내 — 전화번호가 있어도 지킨다", () => {
    expect(adScore(A("지면 22면", "밀입국 관련 주민 신고 안내",
      "대망의 2000년을 목전에 둔 지금, 우리의 국가안보를 위협하고 사회질서를 혼란케 하는 밀입국자들이 증가하고 있습니다. 해상이나 해안에서 거동이 수상한자나 선박을 발견하신 주민께서는 군부대로 신고하시기 바랍니다.\n주민여러분의 많은 협조와 적극적인 신고를 부탁드립니다.(675-0113)\n육군 제1789부대 3대대")).ad).toBe(false);
  });

  // ⚠ '안내'만으로 지키면 안 된다 — 업소 개업 안내는 광고다.
  it("업소 개업 안내는 여전히 광고다", () => {
    expect(adScore(A("지면 16면", "왕과비 개업 안내",
      "그동안 바론당구장에 보내주신 성원과 후의에 깊이 감사드립니다. 금번 같은 장소에 전화 675-1234 개업하였기에 많은 이용 바랍니다")).ad).toBe(true);
  });
});

