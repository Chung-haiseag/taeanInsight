export type FestTriage =
  | "태안"      // 이름이나 근거에 태안 지명이 있다 — 승인 후보
  | "타지역"    // 다른 시·군 축제 — 반려 후보
  | "이름아님"  // 수식어를 축제 이름으로 잡은 것 — 반려 후보
  | "확인필요"; // 지명이 어디에도 없다 — 사람이 본다

export interface FestLike { name: string; evidence?: string[] }

const has = (text: string, words: string[]) => words.some((w) => text.includes(w));

/**
 * 축제 후보 하나를 어디로 보낼지 정한다(순수).
 *
 *   순서가 중요하다. 태안신문 기사라 근거에 '태안'이 스쳐 지나가는 일이 흔해서,
 *   **이름을 먼저** 본다 — '보령머드축제'는 근거에 태안이 있어도 보령 축제다.
 */
export function triageFestival(f: FestLike): FestTriage {
  const name = (f.name ?? "").trim();
  if (!name) return "확인필요";

  if (has(name, OTHER)) return "타지역";
  const stem = name.endsWith("축제") ? name.slice(0, -2) : "";
  if (stem && GENERIC.includes(stem)) return "이름아님";

  const blob = `${name} ${(f.evidence ?? []).join(" ")}`;
  if (has(blob, TAEAN)) return "태안";
  if (has(blob, OTHER)) return "타지역";
  return "확인필요";
}

export interface FestTriageCounts { 태안: number; 타지역: number; 이름아님: number; 확인필요: number }

/** 갈래별로 센다 — 화면에 '몇 건을 자동으로 갈랐는지' 보여주기 위해. */
export function countFestTriage(items: FestLike[]): FestTriageCounts {
  const c: FestTriageCounts = { 태안: 0, 타지역: 0, 이름아님: 0, 확인필요: 0 };
  for (const it of items) c[triageFestival(it)]++;
  return c;
}
